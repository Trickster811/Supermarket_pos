import 'package:dio/dio.dart';
import 'package:flutter/material.dart';
import 'package:supermarket_pos/core/storage/secure_storage.dart';
import 'package:supermarket_pos/features/pairing/pairing_service.dart';
import 'package:supermarket_pos/features/pairing/terminal_home_screen.dart';

class PairingScreen extends StatefulWidget {
  const PairingScreen({super.key});

  @override
  State<PairingScreen> createState() => _PairingScreenState();
}

class _PairingScreenState extends State<PairingScreen> {
  final _formKey = GlobalKey<FormState>();

  final _terminalCodeController = TextEditingController();
  final _pairingCodeController = TextEditingController();

  final _pairingService = PairingService();

  bool _isLoading = false;
  bool _isPaired = false;
  String? _errorMessage;
  String? _pairedTerminalCode;

  @override
  void dispose() {
    _terminalCodeController.dispose();
    _pairingCodeController.dispose();
    super.dispose();
  }

  Future<void> _pairTerminal() async {
    if (!_formKey.currentState!.validate()) return;

    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });

    try {
      final result = await _pairingService.pair(
        terminalCode: _terminalCodeController.text,
        pairingCode: _pairingCodeController.text,
      );

      final terminalId = result['terminalId'] as String?;
      final deviceToken = result['deviceToken'] as String?;
      final terminalCode = result['terminalCode'] as String?;

      if (terminalId == null || deviceToken == null || terminalCode == null) {
        throw Exception('The server returned incomplete pairing credentials.');
      }

      await SecureStorage.saveTerminalCredentials(
        terminalId: terminalId,
        terminalToken: deviceToken,
      );

      if (!mounted) return;

      Navigator.of(context).pushReplacement(
        MaterialPageRoute(builder: (_) => const TerminalHomeScreen()),
      );
    } on DioException catch (error) {
      String message = 'Unable to pair with the server.';

      final responseData = error.response?.data;

      if (responseData is Map && responseData['message'] is String) {
        message = responseData['message'] as String;
      } else if (error.response == null) {
        message = 'Cannot reach the server. Check your network connection.';
      }

      if (mounted) {
        setState(() {
          _errorMessage = message;
        });
      }
    } catch (error) {
      if (mounted) {
        setState(() {
          _errorMessage = error.toString().replaceFirst('Exception: ', '');
        });
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    if (_isPaired) {
      return Scaffold(
        appBar: AppBar(title: const Text('Terminal pairing')),
        body: Center(
          child: Padding(
            padding: const EdgeInsets.all(24),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                const Icon(Icons.check_circle, color: Colors.green, size: 72),
                const SizedBox(height: 16),
                const Text(
                  'Terminal paired successfully!',
                  style: TextStyle(fontSize: 22, fontWeight: FontWeight.bold),
                  textAlign: TextAlign.center,
                ),
                const SizedBox(height: 8),
                Text('Terminal: $_pairedTerminalCode'),
                const SizedBox(height: 24),
                const Text(
                  'This device is now registered as a checkout terminal.',
                  textAlign: TextAlign.center,
                ),
              ],
            ),
          ),
        ),
      );
    }

    return Scaffold(
      appBar: AppBar(title: const Text('Pair checkout terminal')),
      body: Center(
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(24),
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 420),
            child: Form(
              key: _formKey,
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  const Icon(Icons.point_of_sale, size: 72),
                  const SizedBox(height: 20),
                  const Text(
                    'Connect this device to your supermarket',
                    style: TextStyle(fontSize: 22, fontWeight: FontWeight.bold),
                    textAlign: TextAlign.center,
                  ),
                  const SizedBox(height: 8),
                  const Text(
                    'Enter the terminal code and the six-digit pairing '
                    'code generated by your administrator.',
                    textAlign: TextAlign.center,
                  ),
                  const SizedBox(height: 28),

                  TextFormField(
                    controller: _terminalCodeController,
                    textCapitalization: TextCapitalization.characters,
                    decoration: const InputDecoration(
                      labelText: 'Terminal code',
                      hintText: 'POS-001',
                      prefixIcon: Icon(Icons.devices),
                    ),
                    validator: (value) {
                      if (value == null || value.trim().isEmpty) {
                        return 'Enter the terminal code.';
                      }
                      return null;
                    },
                  ),

                  const SizedBox(height: 16),

                  TextFormField(
                    controller: _pairingCodeController,
                    keyboardType: TextInputType.number,
                    maxLength: 6,
                    decoration: const InputDecoration(
                      labelText: 'Six-digit pairing code',
                      hintText: '123456',
                      prefixIcon: Icon(Icons.lock_outline),
                      counterText: '',
                    ),
                    validator: (value) {
                      if (value == null ||
                          !RegExp(r'^\d{6}$').hasMatch(value.trim())) {
                        return 'Enter a valid six-digit pairing code.';
                      }
                      return null;
                    },
                  ),

                  const SizedBox(height: 20),

                  if (_errorMessage != null) ...[
                    Text(
                      _errorMessage!,
                      style: const TextStyle(color: Colors.red),
                      textAlign: TextAlign.center,
                    ),
                    const SizedBox(height: 16),
                  ],

                  FilledButton(
                    onPressed: _isLoading ? null : _pairTerminal,
                    child: _isLoading
                        ? const SizedBox(
                            height: 20,
                            width: 20,
                            child: CircularProgressIndicator(strokeWidth: 2),
                          )
                        : const Text('Pair terminal'),
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }
}
